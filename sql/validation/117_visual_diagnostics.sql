-- @@ cohort_rows
SELECT
    FIPS,
    COUNTY,
    STATE,
    RELEASE_ID,
    POPULATION,
    SVI_PERCENTILE,
    UNINSURED_PERCENTILE,
    RUCC_2023,
    HUMAN_STATUS,
    TICK_STATUS,
    BURGDORFERI_STATUS,
    IN_CONTIGUOUS_TICK_SCOPE
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_COUNTY_ATLAS_V

-- @@ climate_means
SELECT MEASURE_ID, COUNTY_FIPS, AVG(IFF(VALUE_STATE = 'ZERO' AND COALESCE(VALUE_NATIVE_DOUBLE, TRY_TO_DOUBLE(TO_VARCHAR(VALUE))) IS NULL, 0, COALESCE(VALUE_NATIVE_DOUBLE, TRY_TO_DOUBLE(TO_VARCHAR(VALUE))))) AS MEAN_VALUE, COUNT(*) AS N
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_CLIMATE_COUNTY_DAY_OBSERVATIONS_V
WHERE VALUE_STATE IN ('OBSERVED', 'ZERO')
  AND MEASURE_ID IN ('nclimgrid_prcp_county_day', 'nclimgrid_tavg_county_day', 'nclimgrid_tmax_county_day', 'nclimgrid_tmin_county_day')
  AND (COALESCE(VALUE_NATIVE_DOUBLE, TRY_TO_DOUBLE(TO_VARCHAR(VALUE))) IS NOT NULL OR VALUE_STATE = 'ZERO')
GROUP BY MEASURE_ID, COUNTY_FIPS

-- @@ state_day_temperature
SELECT
    ATLAS.STATE AS STATE,
    CAST(DAYS.PERIOD_START AS DATE) AS DAY,
    AVG(DAYS.VAL) AS MEAN_VALUE,
    COUNT(*) AS N
FROM (
    SELECT
        COUNTY_FIPS,
        PERIOD_START,
        IFF(VALUE_STATE = 'ZERO' AND COALESCE(VALUE_NATIVE_DOUBLE, TRY_TO_DOUBLE(TO_VARCHAR(VALUE))) IS NULL, 0, COALESCE(VALUE_NATIVE_DOUBLE, TRY_TO_DOUBLE(TO_VARCHAR(VALUE)))) AS VAL
    FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_CLIMATE_COUNTY_DAY_OBSERVATIONS_V
    WHERE MEASURE_ID = 'nclimgrid_tavg_county_day'
      AND VALUE_STATE IN ('OBSERVED', 'ZERO')
      AND (COALESCE(VALUE_NATIVE_DOUBLE, TRY_TO_DOUBLE(TO_VARCHAR(VALUE))) IS NOT NULL OR VALUE_STATE = 'ZERO')
) AS DAYS
JOIN ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_COUNTY_ATLAS_V AS ATLAS
    ON ATLAS.FIPS = DAYS.COUNTY_FIPS
GROUP BY ATLAS.STATE, CAST(DAYS.PERIOD_START AS DATE)
