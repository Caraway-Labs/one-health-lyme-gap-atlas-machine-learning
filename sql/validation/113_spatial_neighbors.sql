-- @@ release_identity
SELECT
    RELEASE_ID,
    SCHEMA_VERSION,
    BUNDLE_SHA256,
    METHODOLOGY_VERSION,
    SCOPE
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_RELEASE_V

-- @@ source_vintages
SELECT
    SOURCE_KEY,
    VINTAGE
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_SOURCE_METADATA_V

-- @@ adjacency_columns
SELECT
    TABLE_SCHEMA,
    TABLE_NAME,
    COLUMN_NAME
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.INFORMATION_SCHEMA.COLUMNS
WHERE TABLE_SCHEMA IN ('PRESENTATION', 'CONFORMED', 'FEATURE_STORE')
  AND TABLE_NAME NOT ILIKE '%HISTORICAL%'
  AND TABLE_NAME NOT ILIKE '%CDC_LYME%'
  AND TABLE_NAME NOT ILIKE 'RESTRICTED%'
  AND (
      COLUMN_NAME ILIKE '%ADJAC%'
      OR COLUMN_NAME ILIKE '%NEIGHB%'
      OR COLUMN_NAME ILIKE '%CENTROID%'
      OR COLUMN_NAME ILIKE '%LATITUDE%'
      OR COLUMN_NAME ILIKE '%LONGITUDE%'
      OR COLUMN_NAME ILIKE '%BORDER%'
      OR COLUMN_NAME ILIKE '%DISTANCE%'
      OR COLUMN_NAME ILIKE '%TOUCH%'
  )

-- @@ spatial_measures
SELECT
    MEASURE_ID
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_MEASURE_METADATA_V
WHERE MEASURE_ID ILIKE '%ADJAC%'
   OR MEASURE_ID ILIKE '%NEIGHB%'
   OR MEASURE_ID ILIKE '%CENTROID%'
   OR MEASURE_ID = 'county_geometry'

-- @@ adjacency_lab_rows
SELECT
    COUNT(*) AS EDGE_N
FROM ONE_HEALTH_LYME_GAP_ATLAS_ML_LAB.EDA.COUNTY_ADJACENCY_107

