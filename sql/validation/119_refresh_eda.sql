-- Climate and intelligence views are visible, but their row counts are a
-- separate follow-up. They are not latent-class inputs, and a combined count
-- did not return within this pass.

SELECT
    'atlas_grain' AS QUERY_ID,
    COUNT(*) AS N_ROWS,
    COUNT(DISTINCT FIPS) AS DISTINCT_FIPS,
    COUNT(DISTINCT STATE) AS DISTINCT_STATES,
    SUM(IFF(REGEXP_LIKE(FIPS, '^[0-9]{5}$'), 1, 0)) AS FIVE_DIGIT_FIPS,
    SUM(POPULATION) AS POPULATION,
    MIN(POPULATION) AS MIN_POPULATION,
    MAX(POPULATION) AS MAX_POPULATION,
    COUNT(DISTINCT RELEASE_ID) AS DISTINCT_RELEASES,
    SUM(IFF(POPULATION IS NULL OR POPULATION <= 0, 1, 0)) AS BAD_POPULATION,
    SUM(IFF(CASE_COUNT_FLOOR_2023 IS NULL, 1, 0)) AS NULL_CASE_FLOOR,
    SUM(IFF(INCIDENCE_FLOOR_2023 IS NULL, 1, 0)) AS NULL_INCIDENCE_FLOOR,
    SUM(IFF(
        HUMAN_STATUS = 'published_count_floor'
        AND (CASE_COUNT_FLOOR_2023 IS NULL OR INCIDENCE_FLOOR_2023 IS NULL),
        1, 0
    )) AS PUBLISHED_MISSING_FLOOR,
    SUM(IFF(
        HUMAN_STATUS = 'no_county_linked_record'
        AND (CASE_COUNT_FLOOR_2023 IS NOT NULL OR INCIDENCE_FLOOR_2023 IS NOT NULL),
        1, 0
    )) AS BLANK_HUMAN_WITH_FLOOR,
    SUM(IFF(SCAPULARIS_STATUS = 'Established' AND PACIFICUS_STATUS = 'Established', 1, 0))
        AS BOTH_SPECIES_ESTABLISHED,
    SUM(IFF(
        STATE IN ('AK', 'HI')
        AND (
            SCAPULARIS_STATUS <> 'Unknown'
            OR PACIFICUS_STATUS <> 'Unknown'
            OR BURGDORFERI_STATUS <> 'Unknown'
        ),
        1, 0
    )) AS AK_HI_NOT_UNKNOWN,
    SUM(IFF(
        STATE NOT IN ('AK', 'HI')
        AND (
            SCAPULARIS_STATUS = 'Unknown'
            OR PACIFICUS_STATUS = 'Unknown'
            OR BURGDORFERI_STATUS = 'Unknown'
        ),
        1, 0
    )) AS OTHER_STATE_UNKNOWN
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V;

SELECT 'human_status' AS QUERY_ID, HUMAN_STATUS AS LEVEL, COUNT(*) AS N, SUM(POPULATION) AS POPULATION
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V
GROUP BY HUMAN_STATUS
UNION ALL
SELECT 'scapularis_status', SCAPULARIS_STATUS, COUNT(*), SUM(POPULATION)
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V
GROUP BY SCAPULARIS_STATUS
UNION ALL
SELECT 'pacificus_status', PACIFICUS_STATUS, COUNT(*), SUM(POPULATION)
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V
GROUP BY PACIFICUS_STATUS
UNION ALL
SELECT 'burgdorferi_status', BURGDORFERI_STATUS, COUNT(*), SUM(POPULATION)
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V
GROUP BY BURGDORFERI_STATUS
UNION ALL
SELECT 'tick_status', TICK_STATUS, COUNT(*), SUM(POPULATION)
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V
GROUP BY TICK_STATUS
UNION ALL
SELECT 'evidence_completeness', TO_VARCHAR(EVIDENCE_COMPLETENESS), COUNT(*), SUM(POPULATION)
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V
GROUP BY EVIDENCE_COMPLETENESS
ORDER BY QUERY_ID, N DESC;

SELECT
    'four_state' AS QUERY_ID,
    HUMAN_STATUS,
    SCAPULARIS_STATUS,
    PACIFICUS_STATUS,
    BURGDORFERI_STATUS,
    COUNT(*) AS N,
    SUM(POPULATION) AS POPULATION
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V
GROUP BY 2, 3, 4, 5
ORDER BY N DESC;

SELECT
    'rolled_surveillance' AS QUERY_ID,
    HUMAN_STATUS,
    TICK_STATUS,
    BURGDORFERI_STATUS,
    COUNT(*) AS N,
    SUM(POPULATION) AS POPULATION
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V
GROUP BY 2, 3, 4
ORDER BY N DESC;

SELECT
    'alaska_hawaii' AS QUERY_ID,
    STATE,
    COUNT(*) AS N,
    SUM(POPULATION) AS POPULATION,
    COUNT(DISTINCT HUMAN_STATUS) AS HUMAN_LEVELS,
    COUNT(DISTINCT SCAPULARIS_STATUS) AS SCAPULARIS_LEVELS,
    COUNT(DISTINCT PACIFICUS_STATUS) AS PACIFICUS_LEVELS,
    COUNT(DISTINCT BURGDORFERI_STATUS) AS PATHOGEN_LEVELS,
    MIN(SCAPULARIS_STATUS) AS SCAPULARIS_STATUS,
    MIN(PACIFICUS_STATUS) AS PACIFICUS_STATUS,
    MIN(BURGDORFERI_STATUS) AS BURGDORFERI_STATUS,
    MIN(TO_VARCHAR(IN_CONTIGUOUS_TICK_SCOPE)) AS IN_CONTIGUOUS_TICK_SCOPE
FROM PRESENTATION.CURRENT_COUNTY_ATLAS_V
WHERE STATE IN ('AK', 'HI')
GROUP BY STATE
ORDER BY STATE;

