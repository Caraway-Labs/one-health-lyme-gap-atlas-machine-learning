-- @@ state_unallocated_profile
WITH states AS (
    SELECT STATE, MAX(STATE_UNALLOCATED_RECORDS_2023) AS STATE_TOTAL
    FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_COUNTY_ATLAS_V
    GROUP BY STATE
)
SELECT
    COUNT(*) AS ROW_N,
    SUM(IFF(STATE_TOTAL IS NULL, 1, 0)) AS NULL_N,
    COUNT(STATE_TOTAL) AS NON_NULL_N,
    COUNT(DISTINCT STATE_TOTAL) AS DISTINCT_N,
    MIN(STATE_TOTAL) AS MIN_VALUE,
    MAX(STATE_TOTAL) AS MAX_VALUE,
    AVG(STATE_TOTAL) AS MEAN_VALUE,
    STDDEV_SAMP(STATE_TOTAL) AS STDDEV_VALUE,
    PERCENTILE_CONT(0.01) WITHIN GROUP (ORDER BY STATE_TOTAL) AS P01,
    PERCENTILE_CONT(0.05) WITHIN GROUP (ORDER BY STATE_TOTAL) AS P05,
    PERCENTILE_CONT(0.25) WITHIN GROUP (ORDER BY STATE_TOTAL) AS P25,
    PERCENTILE_CONT(0.50) WITHIN GROUP (ORDER BY STATE_TOTAL) AS P50,
    PERCENTILE_CONT(0.75) WITHIN GROUP (ORDER BY STATE_TOTAL) AS P75,
    PERCENTILE_CONT(0.95) WITHIN GROUP (ORDER BY STATE_TOTAL) AS P95,
    PERCENTILE_CONT(0.99) WITHIN GROUP (ORDER BY STATE_TOTAL) AS P99,
    SUM(STATE_TOTAL) AS RECORD_SUM
FROM states

