-- @@ release_identity
SELECT
    RELEASE_ID,
    SCHEMA_VERSION,
    BUNDLE_SHA256,
    METHODOLOGY_VERSION,
    SCOPE
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_RELEASE_V

-- @@ source_vintages
SELECT SOURCE_KEY, VINTAGE
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_SOURCE_METADATA_V
ORDER BY SOURCE_KEY

-- @@ atlas_rows
SELECT
    FIPS,
    COUNTY,
    STATE,
    RELEASE_ID,
    POPULATION,
    HUMAN_STATUS,
    CASE_COUNT_FLOOR_2023,
    INCIDENCE_FLOOR_2023,
    SVI_PERCENTILE,
    UNINSURED_PERCENTILE,
    RUCC_2023
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_COUNTY_ATLAS_V

-- @@ tier_rows
SELECT
    COUNTY_FIPS,
    PRIORITY_TIER,
    PRIORITY_PERCENTILE,
    RAW_MODEL_SCORE,
    EVIDENCE_SUFFICIENCY,
    MODEL_VERSION,
    FEATURE_SET_VERSION,
    EVALUATION_VERSION,
    TIER_POLICY_VERSION,
    PREDICTION_BATCH_VERSION,
    RUN_ID,
    RELEASE_ID,
    HUMAN_EVIDENCE_STATE
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_TIER1_COUNTY_REVIEW_V

-- @@ climate_status
SELECT
    MEASURE_ID,
    VALUE_STATE,
    COUNT(*) AS N,
    MIN(PERIOD_START) AS MIN_START,
    MAX(PERIOD_END) AS MAX_END
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_CLIMATE_COUNTY_DAY_OBSERVATIONS_V
GROUP BY MEASURE_ID, VALUE_STATE
ORDER BY MEASURE_ID, VALUE_STATE

-- @@ climate_values
SELECT
    MEASURE_ID,
    COUNTY_FIPS,
    VALUE_STATE,
    VALUE_NATIVE_DOUBLE
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_CLIMATE_COUNTY_DAY_OBSERVATIONS_V
WHERE VALUE_STATE IN ('OBSERVED', 'ZERO')

-- @@ nlcd_counties
SELECT COUNT(DISTINCT COUNTY_FIPS) AS COUNTY_N
FROM ONE_HEALTH_LYME_GAP_ATLAS_PROD.PRESENTATION.CURRENT_COUNTY_OBSERVATIONS_V
WHERE STARTSWITH(MEASURE_ID, 'nlcd_')
